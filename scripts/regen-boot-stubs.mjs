#!/usr/bin/env node
/**
 * Sync `shell-boot-stubs.js` from en/es pack.json for cold-start chrome keys.
 * Invoked by `locales:pack` (via build-locale-packs.mjs).
 */
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const stubPath = join(ROOT, 'src/stores/shell-boot-stubs.js');
const enPack = JSON.parse(readFileSync(join(ROOT, 'locales/en/pack.json'), 'utf8'));
const esPack = JSON.parse(readFileSync(join(ROOT, 'locales/es/pack.json'), 'utf8'));

/** Cold-start chrome: dock, onboarding, backpack peek, tree-growing, early errors. */
const PREFIXES = [
    'onboarding',
    'nav',
    'moreMenu',
    'menuSection',
    'treeGrowing',
    'progress',
    'gardenVitality',
    'gardenShop',
    'gardenEmpty',
    'arcadeTab',
    'arcadeWater',
    'arcadeHealthy',
    'care',
    'streak',
    'lumens',
    'seedsTitle',
    'certificates',
    'lockedCert',
    'showEarned',
    'showAll',
    'searchCert',
    'viewCert',
    'lessonFinished',
    'mochila',
    'gameLoading',
    'gameEstablishing',
    'gameReading',
    'gameSession',
    'gameDefault',
];

const EXACT = [
    'loading',
    'cancel',
    'close',
    'themeToggle',
    'languageTitle',
    'privacyTitle',
    'a11yPrefsTitle',
    'xpUnit',
    'todayGoal',
    'sourceLoad',
    'noTreesBtnSources',
    'noResults',
    'dialogOkButton',
    'authUsernameRequired',
    'syncLoginNeedUserSecret',
    'syncLoginUsernameTaken',
    'profileSheetTagline',
];

function keep(k) {
    if (EXACT.includes(k)) return true;
    return PREFIXES.some((p) => k === p || k.startsWith(p));
}

const finalKeys = Object.keys(enPack)
    .filter((k) => esPack[k] != null && keep(k))
    .sort();

function emit(langPack) {
    return finalKeys.map((k) => `    ${k}: ${JSON.stringify(String(langPack[k]))},`).join('\n');
}

const out = `import { normalizeAppLangCode } from '../core/i18n.js';

/**
 * First-paint UI strings before \`fetchLocalePack\` resolves.
 * Keep EN/ES key-aligned; values mirror locale pack.json for chrome
 * visible at cold start (dock, onboarding, backpack, tree-growing).
 * Regenerated by \`npm run locales:pack\` (scripts/regen-boot-stubs.mjs).
 */

const ES_UI_BOOT_STUB = {
${emit(esPack)}
};

const EN_UI_BOOT_STUB = {
${emit(enPack)}
};

/** Strings for first paint before \`fetchLocalePack\` resolves. */
export function bootStubForLang(langCode) {
    const isEs = normalizeAppLangCode(langCode) === 'ES';
    const stub = isEs ? ES_UI_BOOT_STUB : EN_UI_BOOT_STUB;
    return { ...stub };
}

export { ES_UI_BOOT_STUB, EN_UI_BOOT_STUB };
`;

writeFileSync(stubPath, out);
console.log(`shell-boot-stubs.js : ${finalKeys.length} keys (EN/ES aligned)`);
